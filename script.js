const categoryNames = {

  coding:
    "Coding & Development",

  business:
    "Business & Analytics",

  event:
    "Event Planning",

  creative:
    "Creative & Design",

  academic:
    "Academic Project"

};


const timeNames = {

  weekend:
    "A weekend",

  week:
    "About 1 week",

  "two-weeks":
    "2–3 weeks",

  month:
    "A month or more"

};


const form =
  document.getElementById("projectForm");


let currentProject = null;


/* ========================================
   GET FORM DATA
======================================== */

function getFormData() {

  const formData =
    new FormData(form);

  return Object.fromEntries(
    formData.entries()
  );

}


/* ========================================
   CHOOSE PROJECT
======================================== */

function chooseProject(category) {

  let pool =
    projects.filter(
      project =>
        project.category === category
    );


  if (!pool.length) {
    pool = projects;
  }


  const alternatives =
    pool.filter(
      project =>
        !currentProject ||
        project.title !== currentProject.title
    );


  const usable =
    alternatives.length
      ? alternatives
      : pool;


  return usable[
    Math.floor(
      Math.random() * usable.length
    )
  ];

}


/* ========================================
   PERSONALIZE PROJECT
======================================== */

function personalizeProject(
  baseProject,
  data
) {

  const project =
    structuredClone(baseProject);


  project.categoryName =
    categoryNames[
      project.category
    ];


  project.userCareer =
    data.career ||
    "your career goals";


  project.userInterest =
    data.interests || "";


  project.time =
    timeNames[data.time] ||
    project.time;


  /*
   * Add the user's existing skills.
   */

  if (data.skills) {

    const userSkills =
      data.skills
        .split(",")
        .map(skill => skill.trim())
        .filter(Boolean);


    project.skills = [
      ...new Set([
        ...userSkills,
        ...project.skills
      ])
    ].slice(0, 7);

  }


  /*
   * Connect the project
   * to the user's career.
   */

  if (data.career) {

    project.build.push(
      `Add a short section explaining how the project connects to ${data.career}`
    );

  }


  /*
   * Connect the project
   * to the user's interests.
   */

  if (data.interests) {

    project.description +=
      ` Personalize the concept around ${data.interests}.`;

  }


  /*
   * Respect things the user
   * wants to avoid.
   */

  if (data.avoid) {

    project.build.push(
      `Keep the scope focused and avoid: ${data.avoid}`
    );

  }


  /*
   * Assignment transformation.
   */

  if (data.assignment) {

    project.title =
      "Assignment → " +
      project.title;


    project.assignmentNote =
      "Use your assignment as the starting point, keep its original requirements, and add real-world context, documentation, or an extra layer of work where appropriate.";

  }


  return project;

}


/* ========================================
   GENERATE
======================================== */

function generateProject() {

  const data =
    getFormData();


  let category =
    data.category;


  if (category === "random") {

    const categories =
      Object.keys(categoryNames);


    category =
      categories[
        Math.floor(
          Math.random() *
          categories.length
        )
      ];

  }


  const baseProject =
    chooseProject(category);


  currentProject =
    personalizeProject(
      baseProject,
      data
    );


  displayProject(
    currentProject
  );

}


/* ========================================
   DISPLAY RESULT
======================================== */

function displayProject(project) {

  document.getElementById(
    "resultTitle"
  ).textContent =
    project.title;


  document.getElementById(
    "resultDescription"
  ).textContent =
    project.description +
    (
      project.assignmentNote
        ? " " + project.assignmentNote
        : ""
    );


  document.getElementById(
    "resultCategory"
  ).textContent =
    project.categoryName;


  document.getElementById(
    "resultDifficulty"
  ).textContent =
    project.difficulty;


  document.getElementById(
    "resultTime"
  ).textContent =
    project.time;


  document.getElementById(
    "resultCareer"
  ).textContent =
    project.userCareer;


  document.getElementById(
    "buildList"
  ).innerHTML =
    project.build
      .map(
        item =>
          `<li>${escapeHTML(item)}</li>`
      )
      .join("");


  document.getElementById(
    "portfolioList"
  ).innerHTML =
    project.portfolio
      .map(
        item =>
          `<li>${escapeHTML(item)}</li>`
      )
      .join("");


  document.getElementById(
    "skillsList"
  ).innerHTML =
    project.skills
      .map(
        skill =>
          `<span>${escapeHTML(skill)}</span>`
      )
      .join("");


  document.getElementById(
    "linkedinText"
  ).textContent =
    createLinkedInDescription(
      project
    );


  const resultSection =
    document.getElementById(
      "resultSection"
    );


  resultSection.classList.remove(
    "hidden"
  );


  resultSection.scrollIntoView({
    behavior: "smooth",
    block: "start"
  });

}


/* ========================================
   LINKEDIN DESCRIPTION
======================================== */

function createLinkedInDescription(
  project
) {

  return `
I built ${project.title}, a ${project.categoryName.toLowerCase()} portfolio project${
    project.userInterest
      ? ` inspired by my interest in ${project.userInterest}`
      : ""
  }.

The project helped me practice ${project.skills
    .slice(0, 4)
    .join(", ")} while creating a finished piece I can use as evidence of what I am learning.

I am continuing to turn coursework and curiosity into practical projects that help me build real experience.
  `.trim();

}


/* ========================================
   ESCAPE HTML
======================================== */

function escapeHTML(value) {

  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll(
      "'",
      "&#039;"
    );

}


/* ========================================
   SAVE PROJECT
======================================== */

function saveProject() {

  if (!currentProject) {
    return;
  }


  const saved =
    JSON.parse(
      localStorage.getItem(
        "portfolioProjects"
      ) || "[]"
    );


  const alreadySaved =
    saved.some(
      project =>
        project.title ===
          currentProject.title &&
        project.userInterest ===
          currentProject.userInterest
    );


  if (alreadySaved) {

    alert(
      "You already saved this project."
    );

    return;

  }


  saved.unshift({

    ...currentProject,

    savedAt:
      new Date().toISOString()

  });


  localStorage.setItem(
    "portfolioProjects",
    JSON.stringify(saved)
  );


  renderSavedProjects();


  const button =
    document.getElementById(
      "saveProject"
    );


  button.textContent =
    "Saved ✓";


  setTimeout(() => {

    button.textContent =
      "Save Project";

  }, 1400);

}


/* ========================================
   RENDER SAVED PROJECTS
======================================== */

function renderSavedProjects() {

  const saved =
    JSON.parse(
      localStorage.getItem(
        "portfolioProjects"
      ) || "[]"
    );


  const container =
    document.getElementById(
      "savedProjects"
    );


  const empty =
    document.getElementById(
      "emptySaved"
    );


  const count =
    document.getElementById(
      "savedCount"
    );


  count.textContent =
    `${saved.length} saved project${
      saved.length === 1
        ? ""
        : "s"
    }`;


  empty.classList.toggle(
    "hidden",
    saved.length > 0
  );


  container.innerHTML =
    saved
      .map(
        (project, index) => `

          <article class="saved-card">

            <small>
              ${escapeHTML(
                project.categoryName
              )}
            </small>

            <h3>
              ${escapeHTML(
                project.title
              )}
            </h3>

            <p>
              ${escapeHTML(
                project.description
              )}
            </p>

            <button
              class="delete-button"
              type="button"
              data-index="${index}"
            >
              Remove project
            </button>

          </article>

        `
      )
      .join("");


  document
    .querySelectorAll(
      ".delete-button"
    )
    .forEach(button => {

      button.addEventListener(
        "click",
        () => {

          const projects =
            JSON.parse(
              localStorage.getItem(
                "portfolioProjects"
              ) || "[]"
            );


          projects.splice(
            Number(
              button.dataset.index
            ),
            1
          );


          localStorage.setItem(
            "portfolioProjects",
            JSON.stringify(projects)
          );


          renderSavedProjects();

        }
      );

    });

}


/* ========================================
   COPY LINKEDIN
======================================== */

async function copyLinkedIn() {

  if (!currentProject) {
    return;
  }


  const text =
    document.getElementById(
      "linkedinText"
    ).textContent;


  try {

    await navigator.clipboard.writeText(
      text
    );


    const button =
      document.getElementById(
        "copyLinkedIn"
      );


    button.textContent =
      "Copied ✓";


    setTimeout(() => {

      button.textContent =
        "Copy description";

    }, 1400);

  }

  catch {

    alert(
      "Copy is not available. You can select the text manually."
    );

  }

}


